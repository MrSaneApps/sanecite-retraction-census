#!/usr/bin/env python3
"""Every figure the paper quotes, from the result files, in one place (paper_numbers.md). Run after the analyses.
usage: SANECITE_DATA=... paper_numbers.py [synthesis verified.json]"""
import json, os, sys
D = os.environ["SANECITE_DATA"]
J = lambda f: json.load(open(f"{D}/{f}"))
R, C, H, S, T = J("census_results.json"), J("coverage_types.json"), J("hs_compare.json"), J("sensitivity.json"), J("retest.json")
pc = lambda x: f"{100 * x:.1f}%"
rate = lambda s: s["k"] / s["n"] if "k" in s else s["rate"]   # exact share; never re-round a rounded rate
ci = lambda c: f"{100 * c[0]:.1f}–{100 * c[1]:.1f}"
st = lambda s: f"{pc(rate(s))} ({ci(s['ci95'])}; n={s['n']:,}" + (f", papers={s['papers']:,})" if "papers" in s else ")")
L = []
w = L.append
w("# Paper numbers (generated by paper_numbers.py; do not edit by hand)\n")
w(f"- frame: pairs classified {R['pairs_classified']:,}; retracted papers read {R['retracted_papers']:,}; judged headline {R['judged']:,}; "
  f"administrative {R['administrative_pairs']:,}; unclear labels {R['unclear'] - R['administrative_pairs']:,}; notices set aside {R['notices_set_aside']}; "
  f"incomplete pairs {R['incomplete_pairs']}")
w(f"- extraction: {R['extraction']}")
w(f"- coverage: later citations {C['citers_total']:,}; read {C['citers_read']:,}; unread {C['citers_unread']:,}")
for k in ("substantive", "perfunctory", "aware"): w(f"- {k}: {st(R[k])}")
w(f"- strict {st(R['substantive_band']['strict'])}; lenient {st(R['substantive_band']['lenient'])}")
w(f"- routes {R['routes']}; review queue {R['human_review_queue']}")
w(f"- corrected (registered): {R['substantive_corrected']}")
w(f"- corrected rescored: {R.get('substantive_corrected_rescored')}")
w(f"- papers: {R['papers_with_any_substantive']}")
w(f"- ref list says retracted: share of read {st(R['ref_list_says_retracted'])}; cited as support {st(R['substantive_despite_ref_list_label'])}; "
  f"aware {st(R['aware_despite_ref_list_label'])}")
w(f"- ref entry word: {S.get('ref_entry_retract_word', {}).get('counts')}")
w(f"- aware, citing year <= 2019: {st(R['aware_hs_window_citing_le_2019'])}")
for sec in ("by_years_after", "by_reason_all", "by_field", "by_retraction_decade"):
    w(f"\n## {sec}")
    for k, v in R[sec].items(): w(f"- {k}: support {st(v['substantive'])}; aware {st(v['aware'])}")
w("\n## by_citing_year (aware)")
w("- " + "; ".join(f"{k} {pc(rate(v['aware']))} (n={v['aware']['n']})" for k, v in R["by_citing_year"].items()))
w(f"\n## coverage\n- reweighted {C['primary_reweighted']}\n- read vs unread {json.dumps(C['read_vs_unread'])}")
w("\n## by citing type")
for t, v in C["by_citing_type"].items(): w(f"- {t}: n={v['n']:,} support {v['substantive']:,} ({pc(v['substantive'] / v['n'])}) aware {v['aware']:,} ({pc(v['aware'] / v['n'])})")
w(f"\n## Hsiao & Schneider\n- {json.dumps({k: H[k] for k in H if k not in ('panel_sizes_contexts',)})}")
w("\n## sensitivity")
for k, v in S.items():
    if k in ("ref_entry_retract_word",): continue
    w(f"- {k}: {json.dumps(v)}")
w(f"\n## retest\n- {json.dumps(T)}")
w(f"\n## cost\n- {R['cost_usd']}; calls {R['calls']}; {R.get('cost_usd_note')}")
syn = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(D), "synthesis_check", "verified.json")
if os.path.exists(syn):
    import collections
    v = json.load(open(syn)); inc = [x for x in v if x["verdict"] == "I"]
    rows = {json.loads(l)["pair_id"]: json.loads(l) for l in open(f"{D}/census_rows.jsonl")}
    ty = collections.Counter("guideline" if "guideline" in x["citing_type"] else "meta-analysis" if "meta-analysis" in x["citing_type"]
                             else "systematic review" if "systematic" in x["citing_type"] else "other" for x in inc)
    papers = {x["pair_id"].split(">")[0] for x in inc}
    reason = collections.Counter(rows[x["pair_id"]]["reason"] for x in inc if x["pair_id"] in rows and x["pair_id"].split(">")[0] in papers)
    preason = collections.Counter({p: None for p in papers})
    pr = collections.Counter(next(rows[x["pair_id"]]["reason"] for x in inc if x["pair_id"].split(">")[0] == p and x["pair_id"] in rows) for p in papers)
    w(f"\n## synthesis check\n- verdicts {dict(collections.Counter(x['verdict'] for x in v))}; types {dict(ty)}; citing docs "
      f"{len({x['citing_pmcid'] for x in inc})}; retracted papers {len(papers)}; papers by reason {dict(pr)}; "
      f"within 2 calendar years {sum((x.get('years_after') or 0) <= 2 for x in inc)}")
open(f"{D}/paper_numbers.md", "w").write("\n".join(L) + "\n")
print(f"{D}/paper_numbers.md", len(L), "lines")
